/** 이름(성 포함 한글)에 놀림 위험 낱말이 있으면 그 낱말, 없으면 null */
export function teaseWord(fullHangul: string): string | null {
  return TEASE_WORDS.find((w) => fullHangul.includes(w)) ?? null;
}
