/** 대표 훈(첫 번째 뜻)만 본다. 健(굳셀 건, 병 없을 건)처럼 부차 뜻 때문에 좋은 글자가 빠지지 않게. */
export function isNegativeMeaning(meaning: string): boolean {
  const primary = meaning.split(',')[0] ?? '';
  return meaningWords(primary).some((w) => NEGATIVE_WORDS.has(w));
}

