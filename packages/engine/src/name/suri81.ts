/** 81을 넘으면 80을 빼서 찾는다 */
export function suri81(n: number): SuriInfo {
  if (!Number.isInteger(n) || n < 1) throw new RangeError('INVALID_SURI');
  let k = n;
  while (k > 81) k -= 80;
  return SURI81[k - 1] as SuriInfo;
}
