describe('원획 표준 대조', () => {
  it('자주 쓰는 한자의 원획이 성명학 표준과 같다', () => {
    const bad: string[] = [];
    for (const tok of REF.split(' ').filter(Boolean)) {
      const ch = tok[0] as string;
      const n = Number(tok.slice(1));
      const h = getHanja(ch);
      if (!h || h.strokes !== n) bad.push(`${ch} ${h?.strokes} ≠ ${n}`);
    }
    expect(bad).toEqual([]);
  });
});
